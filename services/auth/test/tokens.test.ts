/**
 * The contract between this verifier and the Go services' (`identity` in
 * services/dataplane and services/gateway). Tokens signed by a fixed key, each
 * presented at a fixed moment, with the verdict this verifier reaches; the Go
 * tests read the same file and must reach the same verdicts.
 * `UPDATE_TOKENS=1` rewrites it, which is a change to the contract.
 *
 * A case may name the sessions logged out when it is presented (`revoked`):
 * what a service read from picasso-auth's /auth/revoked.
 *
 * The keys below are FIXTURES: they sign nothing but these tokens.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { SignJWT, importJWK, type CryptoKey, type JWK } from 'jose';
import { describe, expect, it } from 'vitest';
import { verifySessionToken } from '../src/verify.js';

const FILE = fileURLToPath(new URL('../testdata/tokens.json', import.meta.url));
const KEYS = {"fixture":{"crv":"Ed25519","d":"x6ewgHDvu4M8TOcP5Vx_s_eGzPEV_dWq83FWFmUQlsE","x":"DBEhXhEJ_ohRahsEAZXrLWyOp2cWJpzdF1epCkeyTUU","kty":"OKP"},"other":{"crv":"Ed25519","d":"YNa0Hnd5s5fRwNhe0IByVI8KnYTi_mBUtCiiLcW7KHA","x":"roGBm9znrkOplVBTK3io9N5qHVMg9Xp1HSBkYJ5VhFY","kty":"OKP"}} as { fixture: JWK; other: JWK };
const ISSUER = 'https://picasso.example';
const T = 1_793_000_000; // seconds; a fixed moment

const publicOf = ({ d: _d, ...pub }: JWK): JWK => ({ ...pub, kid: 'fixture-1', alg: 'EdDSA', use: 'sig' });

async function sign(key: JWK, claims: Record<string, unknown>, over: { iss?: string; aud?: string; iat?: number; exp?: number; alg?: string } = {}) {
  const k = (await importJWK(key, 'EdDSA')) as CryptoKey;
  return new SignJWT({ tenant: 'dev', amr: ['pwd', 'otp'], auth_time: T - 60, sid: 'sid-fixture', ...claims })
    .setProtectedHeader({ alg: over.alg ?? 'EdDSA', kid: 'fixture-1' })
    .setIssuer(over.iss ?? ISSUER)
    .setAudience(over.aud ?? 'picasso')
    .setSubject('pm')
    .setIssuedAt(over.iat ?? T)
    .setExpirationTime(over.exp ?? T + 900)
    .sign(k);
}

async function cases() {
  const valid = await sign(KEYS.fixture, {});
  const [h, p, s] = valid.split('.');
  const tampered = [h, Buffer.from(JSON.stringify({ ...JSON.parse(Buffer.from(p!, 'base64url').toString()), sub: 'admin' })).toString('base64url'), s].join('.');
  const none = [Buffer.from(JSON.stringify({ alg: 'none', typ: 'JWT' })).toString('base64url'), p, ''].join('.');
  const raw: Array<{ name: string; token: string; now: number; revoked?: string[] }> = [
    { name: 'valid, a minute in', token: valid, now: T + 60 },
    { name: 'valid, at the last second of leeway', token: valid, now: T + 900 + 29 },
    { name: 'expired, past the leeway', token: valid, now: T + 900 + 31 },
    { name: 'issued in the future, past the leeway', token: valid, now: T - 120 },
    { name: 'another issuer', token: await sign(KEYS.fixture, {}, { iss: 'https://evil.example' }), now: T + 60 },
    { name: 'another audience', token: await sign(KEYS.fixture, {}, { aud: 'someone-else' }), now: T + 60 },
    { name: 'an hour long', token: await sign(KEYS.fixture, {}, { exp: T + 3600 }), now: T + 60 },
    { name: 'signed by another key under the same kid', token: await sign(KEYS.other, {}), now: T + 60 },
    { name: 'payload altered after signing', token: tampered, now: T + 60 },
    { name: 'alg none', token: none, now: T + 60 },
    { name: 'no tenant', token: await sign(KEYS.fixture, { tenant: undefined }), now: T + 60 },
    { name: 'logged out', token: valid, now: T + 60, revoked: ['sid-fixture'] },
    { name: 'another session logged out', token: valid, now: T + 60, revoked: ['sid-other'] },
    { name: 'logged out, and expired', token: valid, now: T + 900 + 31, revoked: ['sid-fixture'] },
  ];
  const key = (await importJWK(publicOf(KEYS.fixture), 'EdDSA')) as CryptoKey;
  const out = [];
  for (const c of raw) {
    const v = await verifySessionToken(c.token, key, { issuer: ISSUER, now: c.now * 1000, revoked: new Set(c.revoked ?? []) });
    out.push({ ...c, expected: v.ok ? { ok: true, user: v.session.user, tenant: v.session.tenant } : { ok: false, reason: v.reason } });
  }
  return out;
}

describe('the session-token contract with the Go services', () => {
  it('is what this verifier decides', async () => {
    const contract = { note: 'Generated by services/auth/test/tokens.test.ts. Do not edit by hand.', issuer: ISSUER, audience: 'picasso', jwks: { keys: [publicOf(KEYS.fixture)] }, cases: await cases() };
    const written = `${JSON.stringify(contract, null, 1)}\n`;
    if (process.env.UPDATE_TOKENS === '1') writeFileSync(FILE, written);
    expect(readFileSync(FILE, 'utf8')).toBe(written);
  });

  it('refuses everything but the valid token', async () => {
    const c = await cases();
    expect(c.filter((x) => x.expected.ok).map((x) => x.name)).toEqual(['valid, a minute in', 'valid, at the last second of leeway', 'another session logged out']);
    expect(Object.fromEntries(c.filter((x) => !x.expected.ok).map((x) => [x.name, (x.expected as { reason: string }).reason]))).toEqual({
      'expired, past the leeway': 'expired',
      'issued in the future, past the leeway': 'not_yet_valid',
      'another issuer': 'wrong_issuer',
      'another audience': 'wrong_audience',
      'an hour long': 'lifetime_too_long',
      'signed by another key under the same kid': 'invalid_signature',
      'payload altered after signing': 'invalid_signature',
      'alg none': 'unsupported_alg',
      'no tenant': 'malformed',
      'logged out': 'revoked',
      'logged out, and expired': 'expired',
    });
  });
});
